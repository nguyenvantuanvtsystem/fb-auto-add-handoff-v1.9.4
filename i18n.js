// i18n.js — từ điển đa ngôn ngữ dùng chung cho popup + content scripts + background.
// Không chạm DOM khi load; an toàn trong service worker (không dùng document ở top-level).
const I18N_LANG_DEFAULT = "vi";
const I18N_LANGS = ["vi", "en"];
const I18N_LANG_NAMES = { vi: "Tiếng Việt", en: "English" };
let I18N_LANG = I18N_LANG_DEFAULT;
const I18N = { vi: {}, en: {} };

function t(key, params) {
  const dict = (I18N && I18N[I18N_LANG]) || {};
  const fallback = (I18N && I18N[I18N_LANG_DEFAULT]) || {};
  let text = dict[key] !== undefined ? dict[key] : fallback[key];
  if (text === undefined || text === null) return key;
  text = String(text);
  if (params && typeof params === "object") {
    for (const k of Object.keys(params)) {
      text = text.split("{" + k + "}").join(String(params[k] === undefined || params[k] === null ? "" : params[k]));
    }
  }
  return text;
}

async function initI18n() {
  try {
    const s = await chrome.storage.sync.get("uiLang");
    if (s && s.uiLang && I18N[s.uiLang]) I18N_LANG = s.uiLang;
  } catch (_) { }
  return I18N_LANG;
}

async function setUILang(lang) {
  if (!I18N[lang]) return I18N_LANG;
  I18N_LANG = lang;
  try { await chrome.storage.sync.set({ uiLang: lang }); } catch (_) { }
  return I18N_LANG;
}

// Áp dụng data-i18n / data-i18n-ph / data-i18n-html trong popup.
// Ô prompt (data-i18n-once) chỉ áp dụng ở lần đầu để không đè nội dung người dùng đã lưu.
function applyI18n(opts) {
  if (typeof document === "undefined") return;
  const initial = !!(opts && opts.initial);
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    if (!initial && el.hasAttribute("data-i18n-once")) return;
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.getAttribute("data-i18n-html"));
  });
}

